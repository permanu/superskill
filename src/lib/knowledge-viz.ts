import { buildArchitectureNotes } from "./architecture-notes.js";
import { scanRepo } from "./codegraph/scan.js";
import { GENERATED_MARKER, isUneditedGeneratedContent, markdownText, sealGeneratedContent, writeCodeNotes, type WriteCodeNotesResult } from "./code-notes.js";
import { ensureProjectIndex, rebuildProjectIndex, upsertVaultFile } from "./knowledge-index.js";
import { BASE_GENERATED_MARKER, renderProjectBase } from "./obsidian-bases.js";
import { VaultError, VaultFS } from "./vault-fs.js";

export { GENERATED_MARKER };

const DASHBOARD_LINK_LIMIT = 10;

export interface KnowledgeVizResult {
  project: string;
  notes: string[];
  code_notes: WriteCodeNotesResult;
  nodes: number;
  edges: number;
  kept: string[];
}

const ARCHITECTURE_FILES: ReadonlyArray<{ id: string; file: string; related: readonly string[] }> = [
  {
    id: "diag:high",
    file: "architecture/high-level-architecture.md",
    related: ["architecture/low-level-architecture.md", "architecture/data-model-erd.md", "architecture/dataflow.md"],
  },
  {
    id: "diag:low",
    file: "architecture/low-level-architecture.md",
    related: ["architecture/high-level-architecture.md", "architecture/data-model-erd.md", "architecture/dataflow.md"],
  },
  {
    id: "diag:erd",
    file: "architecture/data-model-erd.md",
    related: ["architecture/high-level-architecture.md", "architecture/low-level-architecture.md", "architecture/dataflow.md"],
  },
  {
    id: "diag:flow",
    file: "architecture/dataflow.md",
    related: ["architecture/high-level-architecture.md", "architecture/low-level-architecture.md", "architecture/data-model-erd.md"],
  },
];

const LEGACY_ARTIFACTS: ReadonlyArray<readonly [stem: string, extension: string]> = [
  ["knowledge-graph", "html"],
  ["knowledge-graph", "canvas"],
  [["architecture", "diagrams"].join("-"), "html"],
];

interface NoteList {
  count: number;
  links: string[];
}

function generatedNote(inner: string, related: string[]): string {
  const rel = related.length ? `related:\n${related.map((r) => `  - ${JSON.stringify(r)}`).join("\n")}\n` : "";
  return `---\ntype: architecture\n${rel}---\n\n${GENERATED_MARKER}\n\n${inner}\n`;
}

function withHeading(title: string, body: string): string {
  const trimmed = body.trim();
  return trimmed.startsWith("#") ? trimmed : `# ${markdownText(title)}\n\n${trimmed}`;
}

function wikilinkTarget(vaultRelPath: string): string {
  return vaultRelPath.endsWith(".md") ? vaultRelPath.slice(0, -3) : vaultRelPath;
}

async function listNoteEntries(vaultFs: VaultFS, dir: string): Promise<NoteList> {
  let entries: string[];
  try {
    entries = await vaultFs.list(dir);
  } catch (error) {
    if (error instanceof VaultError && error.code === "FILE_NOT_FOUND") return { count: 0, links: [] };
    throw error;
  }
  const files = entries
    .filter((entry) => entry.endsWith(".md"))
    .sort((a, b) => (a < b ? 1 : a > b ? -1 : 0));
  return { count: files.length, links: files.slice(0, DASHBOARD_LINK_LIMIT).map(wikilinkTarget) };
}

function dashboardSection(heading: string, notes: NoteList): string[] {
  return [`## ${heading} (${notes.count})`, ...notes.links.map((link) => {
    if (!/[\x00-\x1f\x7f-\x9f\u2028\u2029\[\]|#]/.test(link)) return `- [[${link}]]`;
    const href = `${link}.md`.split("/").slice(2).map(encodeURIComponent).join("/");
    return `- [${markdownText(link)}](<${href}>)`;
  })];
}

function renderDashboard(args: {
  slug: string;
  architecture: readonly string[];
  decisions: NoteList;
  learnings: NoteList;
  sessions: NoteList;
  codeNotes: WriteCodeNotesResult;
}): string {
  const { slug } = args;
  const lines = [
    "---",
    "type: index",
    `project: ${JSON.stringify(slug)}`,
    "---",
    "",
    GENERATED_MARKER,
    "",
    `# ${markdownText(slug)}`,
    "",
    `Dashboard for \`${slug}\`, generated by \`superskill graph viz\`. Edited or legacy notes without a verifiable content hash are left unchanged on regeneration.`,
    "",
    "## Scope",
    `- Search: \`path:projects/${slug} <terms>\``,
    `- Graph: filter \`path:projects/${slug}\` (or run \`superskill viz --open --scope-graph\`)`,
    "",
    "## Architecture",
    ...args.architecture.map((path) => `- [[${wikilinkTarget(path)}]]`),
    "",
    ...dashboardSection("Decisions", args.decisions),
    "",
    ...dashboardSection("Learnings", args.learnings),
    "",
    ...dashboardSection("Sessions", args.sessions),
    "",
    "## Code",
    `- \`projects/${slug}/code/\` — ${args.codeNotes.total} generated code notes with Imports / Imported by links (${args.codeNotes.written} written, ${args.codeNotes.skipped} skipped)`,
  ];
  return `${lines.join("\n")}\n`;
}

async function writeGeneratedNote(vaultFs: VaultFS, path: string, content: string): Promise<boolean> {
  let written = false;
  await vaultFs.update(
    path,
    async (existing) => {
      if (await vaultFs.exists(path) && (!existing.includes(`\n${GENERATED_MARKER}\n`) || !isUneditedGeneratedContent(existing))) return existing;
      written = true;
      return content;
    },
    { create: true },
  );
  return written;
}

async function writeGeneratedBase(vaultFs: VaultFS, path: string, content: string): Promise<boolean> {
  let written = false;
  await vaultFs.update(
    path,
    async (existing) => {
      const firstLine = existing.split("\n", 1)[0].replace(/\r$/, "");
      if (await vaultFs.exists(path) && (firstLine !== BASE_GENERATED_MARKER || !isUneditedGeneratedContent(existing))) return existing;
      written = true;
      return content;
    },
    { create: true },
  );
  return written;
}

export async function writeKnowledgeGraphFiles(
  vaultRoot: string,
  slug: string,
  opts?: { codeRoot?: string },
): Promise<KnowledgeVizResult> {
  const vaultFs = new VaultFS(vaultRoot, { projectSlug: slug });
  ensureProjectIndex(vaultRoot, slug);
  const codeRoot = opts?.codeRoot ?? process.cwd();
  const scan = await scanRepo(codeRoot);
  const architecture = buildArchitectureNotes({ slug, scan });
  const noteById = new Map(architecture.notes.map((note) => [note.id, note]));
  const notes: string[] = [];
  const kept: string[] = [];
  for (const spec of ARCHITECTURE_FILES) {
    const note = noteById.get(spec.id);
    if (!note) continue;
    const rel = `projects/${slug}/${spec.file}`;
    notes.push(rel);
    const content = sealGeneratedContent(generatedNote(
      withHeading(note.title, note.body),
      spec.related.map((target) => `projects/${slug}/${target}`),
    ));
    if (await writeGeneratedNote(vaultFs, rel, content)) {
      upsertVaultFile(vaultRoot, rel, content);
    } else {
      kept.push(rel);
    }
  }
  const code_notes = await writeCodeNotes({ vaultFs, slug, codeRoot, scan });
  const dashboardPath = `projects/${slug}/index.md`;
  const dashboard = sealGeneratedContent(renderDashboard({
    slug,
    architecture: notes,
    decisions: await listNoteEntries(vaultFs, `projects/${slug}/decisions`),
    learnings: await listNoteEntries(vaultFs, `projects/${slug}/learnings`),
    sessions: await listNoteEntries(vaultFs, `projects/${slug}/sessions`),
    codeNotes: code_notes,
  }));
  if (await writeGeneratedNote(vaultFs, dashboardPath, dashboard)) {
    upsertVaultFile(vaultRoot, dashboardPath, dashboard);
  } else {
    kept.push(dashboardPath);
  }
  const basePath = `projects/${slug}/views.base`;
  if (!await writeGeneratedBase(vaultFs, basePath, sealGeneratedContent(renderProjectBase(slug), "yaml"))) {
    kept.push(basePath);
  }
  for (const [stem, extension] of LEGACY_ARTIFACTS) {
    const rel = `projects/${slug}/${stem}.${extension}`;
    if (!await vaultFs.exists(rel)) continue;
    try {
      const deleted = await vaultFs.deleteIf(rel, (content) => content.startsWith(`${GENERATED_MARKER}\n`) && isUneditedGeneratedContent(content));
      if (!deleted && await vaultFs.exists(rel)) kept.push(rel);
    } catch (error) {
      if (error instanceof VaultError && error.code === "FILE_NOT_FOUND") continue;
      throw error;
    }
  }
  rebuildProjectIndex(vaultRoot, slug);
  return {
    project: slug,
    notes,
    code_notes,
    nodes: architecture.nodes,
    edges: architecture.edges,
    kept,
  };
}
